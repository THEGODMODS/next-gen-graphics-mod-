/**
 * Build the original GOD ATMOSPHERE Sider 3.5 crowd engine.
 *
 * The engine only uses documented audio.new / sound methods and team-setup
 * notifications. It deliberately does not infer goals, half-time or full-time.
 */
export function buildAtmosphereModule(name, folder) {
  const beds = ["stadium-open-air", "stadium-intimate", "stadium-night", "stadium-cup-final"];
  const bedSet = beds.map((id) => JSON.stringify(id)).join(", ");
  return [
    "-- THEGODMODS original PES 2017 matchday atmosphere: " + name,
    "-- Sider 3.5 audio API only; no undocumented match-event or memory hooks.",
    "local M = {}",
    "local config_path = nil",
    "local asset_root = nil",
    "local valid_beds = { " + bedSet + " }",
    "local settings = { enabled = 0, ambience = 1, bed = \"stadium-open-air\", texture = \"none\", volume = 0.16, texture_volume = 0.035, intensity = 1 }",
    "local intensity_scale = { [0] = 0.55, [1] = 0.75, [2] = 1.0, [3] = 1.12 }",
    "local base_loop = { sound = nil, filename = nil }",
    "local texture_loop = { sound = nil, filename = nil }",
    "local function valid_bed(value, allow_none)",
    "  if allow_none and value == \"none\" then return true end",
    "  for _, bed in ipairs(valid_beds) do if value == bed then return true end end",
    "  return false",
    "end",
    "local function read_settings()",
    "  local next_settings = { enabled = 0, ambience = 1, bed = \"stadium-open-air\", texture = \"none\", volume = 0.16, texture_volume = 0.035, intensity = 1 }",
    "  local file, open_error = io.open(config_path, \"r\")",
    "  if not file then log(\"THEGODMODS " + name + ": audio INI unavailable; ambience remains safely disabled: \" .. tostring(open_error)); return next_settings end",
    "  for line in file:lines() do",
    "    local key, raw = string.match(line, \"^%s*([%w_]+)%s*=%s*([%w%.%-]+)%s*$\")",
    "    if key == \"enabled\" or key == \"ambience\" then",
    "      local value = tonumber(raw)",
    "      if value == 0 or value == 1 then next_settings[key] = value else log(\"THEGODMODS " + name + ": ignored invalid \" .. key) end",
    "    elseif key == \"volume\" or key == \"texture_volume\" then",
    "      local value = tonumber(raw)",
    "      if value and value == value and value ~= math.huge and value ~= -math.huge and value >= 0 and value <= 1 then next_settings[key] = value",
    "      else log(\"THEGODMODS " + name + ": ignored invalid \" .. key) end",
    "    elseif key == \"intensity\" then",
    "      local value = tonumber(raw)",
    "      if value and value == math.floor(value) and value >= 0 and value <= 3 then next_settings.intensity = value",
    "      else log(\"THEGODMODS " + name + ": intensity must be 0-3\") end",
    "    elseif key == \"bed\" then",
    "      if valid_bed(raw, false) then next_settings.bed = raw else log(\"THEGODMODS " + name + ": unknown crowd bed; keeping default\") end",
    "    elseif key == \"texture\" then",
    "      if valid_bed(raw, true) then next_settings.texture = raw else log(\"THEGODMODS " + name + ": unknown texture bed; disabling texture layer\") end",
    "    elseif key then log(\"THEGODMODS " + name + ": unknown audio INI key \" .. key) end",
    "  end",
    "  file:close()",
    "  if next_settings.texture == next_settings.bed then next_settings.texture = \"none\"; log(\"THEGODMODS " + name + ": duplicate texture bed disabled\") end",
    "  return next_settings",
    "end",
    "local function stop_loop(slot)",
    "  local sound = slot.sound",
    "  slot.sound = nil",
    "  slot.filename = nil",
    "  if sound then sound:finish() end",
    "end",
    "local function effective_volume(key)",
    "  local value = settings[key] * intensity_scale[settings.intensity]",
    "  return math.min(1, math.max(0, value))",
    "end",
    "local function start_loop(slot, filename, volume_key, label)",
    "  if slot.sound or settings.enabled == 0 or settings.ambience == 0 or not filename then return end",
    "  local sound, audio_error = audio.new(asset_root .. filename .. \".wav\")",
    "  if not sound then log(\"THEGODMODS " + name + ": could not load \" .. label .. \": \" .. tostring(audio_error)); return end",
    "  slot.sound = sound",
    "  slot.filename = filename",
    "  sound:set_volume(effective_volume(volume_key))",
    "  sound:when_done(function()",
    "    if slot.sound == sound then",
    "      slot.sound = nil",
    "      start_loop(slot, filename, volume_key, label)",
    "    end",
    "  end)",
    "  sound:play()",
    "end",
    "local function apply_settings()",
    "  settings = read_settings()",
    "  if settings.enabled == 0 or settings.ambience == 0 then stop_loop(base_loop); stop_loop(texture_loop); return end",
    "  if base_loop.filename ~= settings.bed then stop_loop(base_loop) end",
    "  if settings.texture == \"none\" or texture_loop.filename ~= settings.texture then stop_loop(texture_loop) end",
    "  if base_loop.sound then base_loop.sound:set_volume(effective_volume(\"volume\")) end",
    "  if texture_loop.sound then texture_loop.sound:set_volume(effective_volume(\"texture_volume\")) end",
    "  start_loop(base_loop, settings.bed, \"volume\", \"main crowd bed\")",
    "  if settings.texture ~= \"none\" then start_loop(texture_loop, settings.texture, \"texture_volume\", \"secondary stadium texture\") end",
    "end",
    "local function on_team_setup(ctx, team_id)",
    "  apply_settings()",
    "  log(\"THEGODMODS " + name + ": team setup received; generic ambience state applied (team id: \" .. tostring(team_id) .. \" )\")",
    "  return nil",
    "end",
    "function M.init(ctx)",
    "  config_path = \"content\\\\GODMODS\\\\Audio\\\\\" .. " + JSON.stringify(folder) + " .. \"\\\\audio.ini\"",
    "  asset_root = \"content\\\\GODMODS\\\\Audio\\\\\" .. " + JSON.stringify(folder) + " .. \"\\\\\"",
    "  ctx.register(\"set_home_team\", on_team_setup)",
    "  ctx.register(\"set_away_team\", on_team_setup)",
    "  log(\"THEGODMODS " + name + ": loaded; audio is opt-in and disabled until enabled = 1 in audio.ini\")",
    "end",
    "return M",
    ""
  ].join("\n");
}
