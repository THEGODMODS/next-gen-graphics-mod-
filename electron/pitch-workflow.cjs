const fs = require("node:fs/promises");
const { constants } = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { pathToFileURL } = require("node:url");
const ID = /^[a-z0-9]+(?:[.-][a-z0-9]+)+$/;
async function loadTools(root) {
  const dir = path.join(root, "tools");
  const [inventory, builder] = await Promise.all([
    import(pathToFileURL(path.join(dir, "pitch-inventory.mjs")).href),
    import(pathToFileURL(path.join(dir, "pitch-module-builder.mjs")).href)
  ]);
  return { inventory, builder };
}
async function scan(stadiumFolder, root) {
  const tools = await loadTools(root);
  return tools.inventory.inventoryPitch(stadiumFolder);
}
async function build({ stadiumFolder, inventory, inventoryPath, replacementPath, moduleId, moduleName, outputParent }, root) {
  if (typeof moduleId !== "string" || !ID.test(moduleId)) throw new Error("Module ID must be lowercase and namespaced, for example studio.my-pitch.");
  if (typeof moduleName !== "string" || !moduleName.trim() || moduleName.trim().length > 100) throw new Error("Enter a module name of 1–100 characters.");
  if (!inventory || inventory.schemaVersion !== 1 || inventory.subtree !== "common/bg/model/bg/pitch" || !Array.isArray(inventory.records)) throw new Error("Pitch inventory is invalid. Scan the stadium folder again.");
  const record = inventory.records.find(item => item.path === inventoryPath && typeof item.sha256 === "string");
  if (!record) throw new Error("Select a regular file from the current pitch inventory.");
  const replacement = path.resolve(replacementPath);
  const stat = await fs.lstat(replacement);
  if (stat.isSymbolicLink() || !stat.isFile()) throw new Error("Replacement must be a regular file, not a symbolic link.");
  if (path.extname(replacement).toLowerCase() !== path.extname(record.path).toLowerCase()) throw new Error("Replacement extension must match the selected stadium resource.");
  const parent = await fs.realpath(outputParent);
  const parentStat = await fs.lstat(parent);
  if (!parentStat.isDirectory() || parentStat.isSymbolicLink()) throw new Error("Package destination must be a real directory.");
  const outputPath = path.join(parent, moduleId);
  try { await fs.lstat(outputPath); throw new Error("A package with this module ID already exists in the selected destination. Choose another destination; existing files are never overwritten."); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), "nextgen-pitch-"));
  try {
    const sourceDir = path.join(temp, "source");
    await fs.mkdir(sourceDir);
    const sourceName = "replacement" + path.extname(record.path).toLowerCase();
    await fs.copyFile(replacement, path.join(sourceDir, sourceName), constants.COPYFILE_EXCL);
    const descriptor = {
      schemaVersion: 1, id: moduleId, name: moduleName.trim(), version: "1.0.0",
      description: "Private-use Stadium Server pitch resource replacement generated by PES 2017 Next Gen.",
      license: { id: "User-supplied asset; private-use package", redistributionAllowed: false },
      replacements: [{ inventoryPath: record.path, originalSha256: record.sha256, replacementFile: "source/" + sourceName }]
    };
    const descriptorPath = path.join(temp, "pitch-descriptor.json");
    const inventoryFile = path.join(temp, "pitch-inventory.json");
    await fs.writeFile(descriptorPath, JSON.stringify(descriptor, null, 2), { flag: "wx" });
    await fs.writeFile(inventoryFile, JSON.stringify(inventory), { flag: "wx" });
    const tools = await loadTools(root);
    return await tools.builder.buildPitchModule({ descriptorPath, inventoryPath: inventoryFile, outputPath, stadiumFolder });
  } finally {
    await fs.rm(temp, { recursive: true, force: true });
  }
}
module.exports = { scan, build };
